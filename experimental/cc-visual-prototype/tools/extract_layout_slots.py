"""Export the attachment slots of the city house layouts the overlay draws slot by slot (read-only).

Writes ui/cc-layout-slots.js: globalThis.CCLayoutSlots = { LAYOUT_NAME: [[model, x, y, z, turn, scale, kind], ...] }
with positions in tile units (x east, y north), turns in degrees counter-clockwise. Slots that carry another
LAYOUT_ are expanded into that layout's slots (transforms composed). Only asset names and numbers are written.

Record format (see tools/decode_layouts.py): a 40-byte transform record (u64 sequence, f32 0, x, y, z, 0, 0,
turn in radians, scale) followed by a 32-byte name record (u64 sequence, u32 FNV-1a hash of the attachment's
full name, u32 hash of the model it carries, u64 0, u64 kind).

Usage: python -I extract_layout_slots.py
"""
import glob
import json
import math
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_building_art as E  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "ui", "cc-layout-slots.js")
TILE = 64.0
LAYOUTS = [
    "LAYOUT_CTY_MOD_Section_AB_Small_Packed",
    "LAYOUT_CTY_MOD_Section_AB_Small_Packed_FOL",
    "LAYOUT_CTY_EXP_Hex_Section_AB",
    "LAYOUT_CTY_EXP_Hex_Section_AB_VAR_A",
    "LAYOUT_CTY_EXP_Hex_Section_AB_Attatchment",
    "LAYOUT_CTY_EXP_Hex_Section_AB_Attatchment_Less",
    "LAYOUT_CTY_EXP_Hex_Section_AB_Attatchment_Less_FOL",
    # Street pattern B (drawn where the engine's Antiquity streets underneath are B, see ui/cc-street-table.js)
    "LAYOUT_CTY_EXP_Hex_Section_AB_B",
    "LAYOUT_CTY_EXP_Hex_Section_AB_B_VAR_A",
    "LAYOUT_CTY_EXP_Hex_Section_AB_B_Attachment_Less",
    "LAYOUT_CTY_EXP_Hex_Section_AB_B_Attachment_Less_FOL",
]


def load():
    argv, sys.argv = sys.argv, sys.argv[:1]  # find_base reads argv[1] as the game folder
    base = E.find_base()
    sys.argv = argv
    files = sorted(glob.glob(os.path.join(base, "Platforms", "Windows", "BLPs", "*.blp")))
    names, packs = {}, []
    for f in files:
        data = open(f, "rb").read()
        packs.append(data)
        for m in E.STRING.finditer(data):
            s = m.group().decode()
            names.setdefault(E.fnv1a(s), s)
    return names, packs


def raw_slots(layout, names, packs):
    prefix = layout + "_DirectAttachment_"
    for data in packs:
        if prefix.encode() not in data:
            continue
        out = []
        for full in sorted({s for s in E.string_table(data) if s.startswith(prefix)}):
            p = data.find(struct.pack("<I", E.fnv1a(full)))
            if p < 48:
                continue
            child = names.get(struct.unpack_from("<I", data, p + 4)[0])
            kind = struct.unpack_from("<Q", data, p + 16)[0]
            _, x, y, z, _, _, turn, scale = struct.unpack_from("<8f", data, p - 8 - 40 + 8)
            if child:
                out.append([child, x / TILE, y / TILE, z / TILE, math.degrees(turn), scale, kind])
        if out:
            return out
    return []


def slots(layout, names, packs, depth=0):
    out = []
    for child, x, y, z, turn, scale, kind in raw_slots(layout, names, packs):
        if child.startswith("LAYOUT_") and depth < 3 and "_Road" not in child:
            r = math.radians(turn)
            for c2, x2, y2, z2, t2, s2, k2 in slots(child, names, packs, depth + 1):
                out.append([c2, x + scale * (x2 * math.cos(r) - y2 * math.sin(r)),
                            y + scale * (x2 * math.sin(r) + y2 * math.cos(r)), z + scale * z2, turn + t2, scale * s2, k2])
        else:
            out.append([child, x, y, z, turn, scale, kind])
    return [[c, round(x, 4), round(y, 4), round(z, 4), round(((t + 180) % 360) - 180, 1), round(s, 4), k]
            for c, x, y, z, t, s, k in out]


def main():
    names, packs = load()
    table = {}
    for layout in LAYOUTS:
        table[layout] = slots(layout, names, packs)
        print(f"{layout}: {len(table[layout])} slots")
    out = "// Generated by tools/extract_layout_slots.py from the installed game. Asset names and numbers only.\n"
    out += "// LAYOUT -> [[model, x, y, z, turn, scale, kind], ...]; tile units, degrees counter-clockwise.\n"
    out += "globalThis.CCLayoutSlots = " + json.dumps(table, separators=(",", ":")) + ";\n"
    open(OUT, "w", encoding="utf-8", newline="\n").write(out)
    print(os.path.normpath(OUT))


if __name__ == "__main__":
    main()
