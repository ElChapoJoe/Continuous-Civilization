"""Merge measured street tables (street-table-<size>-<seed>.json) into ui/cc-street-table.js for the overlay.

  python build_street_table.py [min_margin]

Every street-table-*.json in tools/data is read; its size comes from the file name (tiny 60x38, small 74x46, ...).
Tables of the same size are merged, leaving out each map's river tiles ("rivers"); a coordinate whose maps disagree (both above min_margin) is left unknown and
reported. Output: one string per map size, one character per plot (row-major): '.' unknown, otherwise
ALPHABET[bare * 5 + wooded] with bare/wooded an index into BARE/WOOD below, 4 = unknown.
"""
import glob
import json
import os
import re
import sys

MIN = float(sys.argv[1]) if len(sys.argv) > 1 else 2.5
SIZES = {"tiny": (60, 38), "small": (74, 46), "standard": (84, 54), "large": (96, 60), "huge": (106, 66)}
BARE = ["A0", "A60", "B0", "B300"]
WOOD = ["A0", "A60", "B0", "B60"]
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXY"   # 25 = 5 x 5
here = os.path.dirname(os.path.abspath(__file__))
merged = {}
for path in sorted(glob.glob(os.path.join(here, "..", "data", "street-table-*.json"))):
    if re.search(r"-(exploration|modern)\.json$", path):
        continue   # later-Age tables, merged below
    size = re.match(r"street-table-([a-z]+)-", os.path.basename(path)).group(1)
    table = json.load(open(path))
    tiles, rivers = table["tiles"], set(table.get("rivers", []))
    m = merged.setdefault(size, {})
    conflicts = 0
    for k, (b, mb, w, mw) in tiles.items():
        if k in rivers:   # a river tile's turn depends on the river, not the coordinate (round 48)
            continue
        for layer, lab, mar, names in ((0, b, mb, BARE), (1, w, mw, WOOD)):
            if mar < MIN or lab not in names:
                continue
            cell = m.setdefault(k, [None, None])
            if cell[layer] is None:
                cell[layer] = lab
            elif cell[layer] != lab:
                cell[layer] = "conflict"
                conflicts += 1
    print("%s: %s, %d tiles, %d conflicts so far" % (size, os.path.basename(path), len(tiles), conflicts))
out = {}
for size, m in merged.items():
    w, h = SIZES[size]
    chars = []
    known = [0, 0]
    for y in range(h):
        for x in range(w):
            cell = m.get("%d,%d" % (x, y), [None, None])
            b = BARE.index(cell[0]) if cell[0] in BARE else 4
            v = WOOD.index(cell[1]) if cell[1] in WOOD else 4
            known[0] += b < 4
            known[1] += v < 4
            chars.append("." if b == 4 and v == 4 else ALPHABET[b * 5 + v])
    out["%dx%d" % (w, h)] = "".join(chars)
    print("%s %dx%d: bare known %d, wooded known %d of %d plots" % (size, w, h, known[0], known[1], w * h))
# Later Ages: vanilla games of that Age measured with that Age's own street models (street-table-<size>-<seed>-<age>.json).
# The engine picks their streets per coordinate too, but by its own bits, unrelated to the Antiquity table (round 58).
# Stored per Age and size as two strings (bare, wooded), one character per plot: '.' unknown, else LABELS[index].
LABELS = ["A%d" % a for a in range(0, 360, 60)] + ["B%d" % a for a in range(0, 360, 60)]
LCHARS = "abcdefghijkl"
ages = {}
for path in sorted(glob.glob(os.path.join(here, "..", "data", "street-table-*-*-*.json"))):
    mm = re.match(r"street-table-([a-z]+)-[0-9a-z]+-(exploration|modern)\.json$", os.path.basename(path))
    if not mm:
        continue
    size, age = mm.groups()
    table = json.load(open(path))
    tiles, rivers = table["tiles"], set(table.get("rivers", []))
    m = ages.setdefault(age, {}).setdefault(size, {})
    conflicts = 0
    for k, (b, mb, w, mw) in tiles.items():
        if k in rivers:
            continue
        for layer, lab, mar in ((0, b, mb), (1, w, mw)):
            if lab is None or mar < MIN or lab not in LABELS:
                continue
            cell = m.setdefault(k, [None, None])
            if cell[layer] is None:
                cell[layer] = lab
            elif cell[layer] != lab:
                cell[layer] = "conflict"
                conflicts += 1
    print("%s %s: %s, %d tiles, %d conflicts so far" % (age, size, os.path.basename(path), len(tiles), conflicts))
age_out = {}
for age, sizes in ages.items():
    for size, m in sizes.items():
        w, h = SIZES[size]
        layers = []
        for layer in (0, 1):
            layers.append("".join(LCHARS[LABELS.index(m["%d,%d" % (x, y)][layer])]
                                  if m.get("%d,%d" % (x, y), [None, None])[layer] in LABELS else "."
                                  for y in range(h) for x in range(w)))
        age_out.setdefault(age, {})["%dx%d" % (w, h)] = layers
        print("%s %s %dx%d: bare known %d, wooded known %d of %d plots" % (
            age, size, w, h, sum(c != "." for c in layers[0]), sum(c != "." for c in layers[1]), w * h))
js = """// Generated by tools/analysis/build_street_table.py from the measured street tables (tools/data/street-table-*.json).
// The Antiquity street pattern the engine paints on an urban tile is fixed per map size and coordinate: a turn shared
// by bare and wooded tiles, and an A/B street layout for each (wooded = forest, rainforest, savanna woodland, taiga,
// sagebrush steppe). River tiles keep the A/B pick, but only river sources (112 of 113) and sharp bends (11 of 11)
// reliably keep the turn (rounds 51-52);
// mouths and middles often turn 60 degrees more (rounds 48-51). Labels are what our own script-drawn street must be to
// match: street A or B at that angle
// (LAYOUT_CTY_Hex_Section_AB_Road_ANT / ..._AB_B_Road_ANT). Coordinates never measured return null.
//   CCStreetTable.lookup(x, y, wooded)   -> { street: "A" | "B", angle, river, sure } or null
//     river: false | "source" | "bend" | "mouth" | "middle" | "navigable" (from MapRivers; bend = sharp 60-degree bend);
//     sure: false when the angle may be 60 degrees off (mouths and other middles flip 40 to 55 percent of the time)
//   CCStreetTable.lookupAge(age, x, y, wooded)  age 1 Exploration, 2 Modern: the street the engine itself draws there in
//     that Age (measured in vanilla games of that Age with that Age's street models), same shape, or null.
(function () {
  const BARE = %s, WOOD = %s, ALPHABET = "%s";
  const DATA = %s;
  const LABELS = %s, LCHARS = "%s", AGES = %s;
  let riverKinds = null, riverKey = null;
  function riverKind(x, y) {   // where a river tile sits on its river: source (one river neighbour), mouth or middle
    if (!GameplayMap.isRiver(x, y)) return false;
    if (GameplayMap.isNavigableRiver(x, y)) return "navigable";
    const w = GameplayMap.getGridWidth(), key = Configuration.getMap().mapSeed + ":" + w;
    if (riverKey !== key && typeof MapRivers !== "undefined") {
      riverKinds = {}; riverKey = key;
      for (let i = 0; i < MapRivers.numRivers; i++) {
        const plots = MapRivers.getRiverPlots(MapRivers.getRiverIDByIndex(i)) || [];
        const pts = plots.map((p) => ({ x: p %% w, y: Math.floor(p / w) }));
        pts.forEach((p, j) => {
          if (GameplayMap.isNavigableRiver(p.x, p.y)) return;
          const adj = (q) => q && GameplayMap.getPlotDistance(p.x, p.y, q.x, q.y) === 1;
          const mouth = j === 0 || GameplayMap.isNavigableRiver(pts[j - 1].x, pts[j - 1].y);
          const links = [pts[j - 1], pts[j + 1]].filter(adj).length;
          const bend = links === 2 && GameplayMap.getPlotDistance(pts[j - 1].x, pts[j - 1].y, pts[j + 1].x, pts[j + 1].y) === 1;
          riverKinds[p.x + "," + p.y] = mouth ? "mouth" : links <= 1 ? "source" : bend ? "bend" : "middle";
        });
      }
    }
    return (riverKinds && riverKinds[x + "," + y]) || "middle";
  }
  function lookup(x, y, wooded) {
    const w = GameplayMap.getGridWidth(), h = GameplayMap.getGridHeight();
    const s = DATA[w + "x" + h];
    if (!s || x < 0 || y < 0 || x >= w || y >= h) return null;
    const c = s[y * w + x];
    if (c === ".") return null;
    const i = ALPHABET.indexOf(c), b = Math.floor(i / 5), v = i %% 5;
    const lab = wooded ? (v < 4 ? WOOD[v] : null) : (b < 4 ? BARE[b] : null);
    if (!lab) return null;
    const river = riverKind(x, y);
    return { street: lab[0], angle: Number(lab.slice(1)), river, sure: !river || river === "source" || river === "bend" };
  }
  function lookupAge(age, x, y, wooded) {
    const t = AGES[age === 1 ? "exploration" : age === 2 ? "modern" : ""];
    const w = GameplayMap.getGridWidth(), h = GameplayMap.getGridHeight();
    const s = t && t[w + "x" + h];
    if (!s || x < 0 || y < 0 || x >= w || y >= h) return null;
    const c = s[wooded ? 1 : 0][y * w + x];
    if (c === ".") return null;
    const lab = LABELS[LCHARS.indexOf(c)];
    const river = riverKind(x, y);
    return { street: lab[0], angle: Number(lab.slice(1)), river, sure: !river || river === "source" || river === "bend" };
  }
  globalThis.CCStreetTable = { lookup, lookupAge, riverKind, sizes: Object.keys(DATA) };
})();
""" % (json.dumps(BARE), json.dumps(WOOD), ALPHABET, json.dumps(out, indent=1), json.dumps(LABELS), LCHARS, json.dumps(age_out, indent=1))
dest = os.path.join(here, "..", "..", "ui", "cc-street-table.js")
open(dest, "w", newline="\n").write(js)
print("wrote", os.path.normpath(dest), len(js), "bytes")
