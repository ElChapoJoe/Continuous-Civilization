"""Merge measured street tables (street-table-<size>-<seed>.json) into ui/cc-street-table.js for the overlay.

  python build_street_table.py [min_margin]

Every street-table-*.json in this folder is read; its size comes from the file name (tiny 60x38, small 74x46, ...).
Tables of the same size are merged, leaving out each map's river tiles ("rivers"); a coordinate whose maps disagree (both above min_margin) is left unknown and
reported. Output: one string per map size, one character per plot (row-major): '.' unknown, otherwise
ALPHABET[bare * 5 + wooded] with bare/wooded an index into BARE/WOOD below, 4 = unknown.
"""
import glob
import json
import os
import re
import sys

MIN = float(sys.argv[1]) if len(sys.argv) > 1 else 2.5
SIZES = {"tiny": (60, 38), "small": (74, 46), "standard": (84, 54), "large": (96, 60), "huge": (106, 66)}
BARE = ["A0", "A60", "B0", "B300"]
WOOD = ["A0", "A60", "B0", "B60"]
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXY"   # 25 = 5 x 5
here = os.path.dirname(os.path.abspath(__file__))
merged = {}
for path in sorted(glob.glob(os.path.join(here, "street-table-*.json"))):
    size = re.match(r"street-table-([a-z]+)-", os.path.basename(path)).group(1)
    table = json.load(open(path))
    tiles, rivers = table["tiles"], set(table.get("rivers", []))
    m = merged.setdefault(size, {})
    conflicts = 0
    for k, (b, mb, w, mw) in tiles.items():
        if k in rivers:   # a river tile's turn depends on the river, not the coordinate (round 48)
            continue
        for layer, lab, mar, names in ((0, b, mb, BARE), (1, w, mw, WOOD)):
            if mar < MIN or lab not in names:
                continue
            cell = m.setdefault(k, [None, None])
            if cell[layer] is None:
                cell[layer] = lab
            elif cell[layer] != lab:
                cell[layer] = "conflict"
                conflicts += 1
    print("%s: %s, %d tiles, %d conflicts so far" % (size, os.path.basename(path), len(tiles), conflicts))
out = {}
for size, m in merged.items():
    w, h = SIZES[size]
    chars = []
    known = [0, 0]
    for y in range(h):
        for x in range(w):
            cell = m.get("%d,%d" % (x, y), [None, None])
            b = BARE.index(cell[0]) if cell[0] in BARE else 4
            v = WOOD.index(cell[1]) if cell[1] in WOOD else 4
            known[0] += b < 4
            known[1] += v < 4
            chars.append("." if b == 4 and v == 4 else ALPHABET[b * 5 + v])
    out["%dx%d" % (w, h)] = "".join(chars)
    print("%s %dx%d: bare known %d, wooded known %d of %d plots" % (size, w, h, known[0], known[1], w * h))
js = """// Generated by tools/build_street_table.py from the measured street tables (tools/street-table-*.json).
// The Antiquity street pattern the engine paints on an urban tile is fixed per map size and coordinate: a turn shared
// by bare and wooded tiles, and an A/B street layout for each (wooded = forest, rainforest, savanna woodland, taiga,
// sagebrush steppe). River tiles keep the A/B pick, but only river sources reliably keep the turn (71 of 71, round 51);
// mouths and middles often turn 60 degrees more (rounds 48-51). Labels are what our own script-drawn street must be to
// match: street A or B at that angle
// (LAYOUT_CTY_Hex_Section_AB_Road_ANT / ..._AB_B_Road_ANT). Coordinates never measured return null.
//   CCStreetTable.lookup(x, y, wooded)   -> { street: "A" | "B", angle, river, sure } or null
//     river: false | "source" | "mouth" | "middle" | "navigable" (from MapRivers); sure: false when the angle may be 60 degrees off
(function () {
  const BARE = %s, WOOD = %s, ALPHABET = "%s";
  const DATA = %s;
  let riverKinds = null, riverKey = null;
  function riverKind(x, y) {   // where a river tile sits on its river: source (one river neighbour), mouth or middle
    if (!GameplayMap.isRiver(x, y)) return false;
    if (GameplayMap.isNavigableRiver(x, y)) return "navigable";
    const w = GameplayMap.getGridWidth(), key = Configuration.getMap().mapSeed + ":" + w;
    if (riverKey !== key && typeof MapRivers !== "undefined") {
      riverKinds = {}; riverKey = key;
      for (let i = 0; i < MapRivers.numRivers; i++) {
        const plots = MapRivers.getRiverPlots(MapRivers.getRiverIDByIndex(i)) || [];
        const pts = plots.map((p) => ({ x: p %% w, y: Math.floor(p / w) }));
        pts.forEach((p, j) => {
          if (GameplayMap.isNavigableRiver(p.x, p.y)) return;
          const adj = (q) => q && GameplayMap.getPlotDistance(p.x, p.y, q.x, q.y) === 1;
          const mouth = j === 0 || GameplayMap.isNavigableRiver(pts[j - 1].x, pts[j - 1].y);
          const links = [pts[j - 1], pts[j + 1]].filter(adj).length;
          riverKinds[p.x + "," + p.y] = mouth ? "mouth" : links <= 1 ? "source" : "middle";
        });
      }
    }
    return (riverKinds && riverKinds[x + "," + y]) || "middle";
  }
  function lookup(x, y, wooded) {
    const w = GameplayMap.getGridWidth(), h = GameplayMap.getGridHeight();
    const s = DATA[w + "x" + h];
    if (!s || x < 0 || y < 0 || x >= w || y >= h) return null;
    const c = s[y * w + x];
    if (c === ".") return null;
    const i = ALPHABET.indexOf(c), b = Math.floor(i / 5), v = i %% 5;
    const lab = wooded ? (v < 4 ? WOOD[v] : null) : (b < 4 ? BARE[b] : null);
    if (!lab) return null;
    const river = riverKind(x, y);
    return { street: lab[0], angle: Number(lab.slice(1)), river, sure: !river || river === "source" };
  }
  globalThis.CCStreetTable = { lookup, riverKind, sizes: Object.keys(DATA) };
})();
""" % (json.dumps(BARE), json.dumps(WOOD), ALPHABET, json.dumps(out, indent=1))
dest = os.path.join(here, "..", "ui", "cc-street-table.js")
open(dest, "w", newline="\n").write(js)
print("wrote", os.path.normpath(dest), len(js), "bytes")
