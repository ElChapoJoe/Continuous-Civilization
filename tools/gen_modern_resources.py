"""Generate the Modern-resource staging data for the continuous-civ mod.

Modern resources sit on the map from turn 1 but stay inactive until a player researches the tech mapped to
each one (data/65-modern-resources.sql). Their Modern-Age effects cannot simply be imported: Modern's
resources-gameeffects files re-define many ids that the Exploration import already adds, and Modern's
ResourcesText re-defines Exploration's text tags. So this script reads (read-only) the installed Modern
module and writes only what is needed, as staging rows that 65-modern-resources.sql turns into tech-gated,
per-player modifiers:

  mod/continuous-civ/data/64-modern-resource-data.sql   every Modern resource modifier that has a
                                                        ResourceType argument (id, collection, effect,
                                                        arguments, subject requirements)
  mod/continuous-civ/text/64-modern-resources-text.sql  Modern resource tooltips (LOC_MOD_RESOURCE_*)

Re-run after every game patch:  python -I tools/gen_modern_resources.py "<Civ7 install>/Base"
"""
import os, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.join(HERE, "..", "mod", "continuous-civ")
BASE = sys.argv[1] if len(sys.argv) > 1 else r"G:\SteamLibrary\steamapps\common\Sid Meier's Civilization VII\Base"
AGE = os.path.join(BASE, "modules", "age-modern")

def strip(t): return t.split("}")[-1]
def q(s): return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"
def kids(e, tag): return [c for c in e if strip(c.tag) == tag]

mods, args, reqs, reqargs = [], [], [], []
for f in ("resources-gameeffects.xml", "resources-gameeffects-v2.xml"):
    p = os.path.join(AGE, "data", f)
    if not os.path.exists(p): continue
    for m in ET.parse(p).getroot():
        if strip(m.tag) != "Modifier": continue
        a = {x.get("name"): (x.text or "").strip() for x in kids(m, "Argument")}
        if "ResourceType" not in a: continue
        if kids(m, "OwnerRequirements"):
            sys.exit(f"{m.get('id')}: owner requirements are not supported")
        mid = m.get("id")
        mods.append((mid, a["ResourceType"], m.get("collection"), m.get("effect"),
                     1 if m.get("permanent") == "true" else 0, 1 if m.get("run-once") == "true" else 0))
        args += [(mid, n, v) for n, v in a.items()]
        for sr in kids(m, "SubjectRequirements"):
            for i, r in enumerate(kids(sr, "Requirement")):
                reqs.append((mid, i, r.get("type"), 1 if r.get("inverse") == "true" else 0))
                reqargs += [(mid, i, x.get("name"), (x.text or "").strip()) for x in kids(r, "Argument")]

out = ["-- GENERATED by tools/gen_modern_resources.py from the installed age-modern module. Do not edit.",
       "-- Staging rows for 65-modern-resources.sql (dropped in 99-cleanup.sql).",
       "DROP TABLE IF EXISTS cc_mres_mods;",
       "CREATE TABLE cc_mres_mods (ModifierId TEXT PRIMARY KEY, ResourceType TEXT, CollectionType TEXT, EffectType TEXT, Permanent INTEGER, RunOnce INTEGER);",
       "DROP TABLE IF EXISTS cc_mres_args;",
       "CREATE TABLE cc_mres_args (ModifierId TEXT, Name TEXT, Value TEXT);",
       "DROP TABLE IF EXISTS cc_mres_reqs;",
       "CREATE TABLE cc_mres_reqs (ModifierId TEXT, Seq INTEGER, RequirementType TEXT, Inverse INTEGER);",
       "DROP TABLE IF EXISTS cc_mres_reqargs;",
       "CREATE TABLE cc_mres_reqargs (ModifierId TEXT, Seq INTEGER, Name TEXT, Value TEXT);"]
for t, rows in (("cc_mres_mods", mods), ("cc_mres_args", args), ("cc_mres_reqs", reqs), ("cc_mres_reqargs", reqargs)):
    for r in rows:
        out.append(f"INSERT INTO {t} VALUES ({', '.join(q(v) if not isinstance(v, int) else str(v) for v in r)});")
open(os.path.join(MOD, "data", "64-modern-resource-data.sql"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

texts = {}
for f in ("ResourcesText.xml", "ResourcesText-v2.xml"):
    p = os.path.join(AGE, "text", "en_us", f)
    if not os.path.exists(p): continue
    for r in ET.parse(p).getroot().iter():
        tag = r.get("Tag")
        if strip(r.tag) == "Row" and tag and tag.startswith("LOC_MOD_RESOURCE_") and tag.endswith("_TOOLTIP"):
            t = [c for c in r if strip(c.tag) == "Text"]
            texts[tag] = (t[0].text if t else r.get("Text")) or ""
tout = ["-- GENERATED by tools/gen_modern_resources.py from the installed age-modern module. Do not edit.",
        "-- Modern resource tooltips (not defined in Antiquity). 65-modern-resources-text.sql adds the tech note."]
for tag in sorted(texts):
    tout.append(f"INSERT OR REPLACE INTO LocalizedText (Language, Tag, Text) VALUES ('en_US', {q(tag)}, {q(texts[tag])});")
open(os.path.join(MOD, "text", "64-modern-resources-text.sql"), "w", encoding="utf-8", newline="\n").write("\n".join(tout) + "\n")
print(f"modifiers {len(mods)}, arguments {len(args)}, requirements {len(reqs)}, tooltips {len(texts)}")
