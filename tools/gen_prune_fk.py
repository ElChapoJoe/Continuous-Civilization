"""Generates mod/continuous-civ/data/3-merge/95-prune-dangling-fk.sql from the installed game's gameplay schema.

Safety net for the game's foreign-key validation: after all of the mod's imports and rules, any row whose
foreign-key column names something that is not in the database is deleted, so a game with DLC or other mods
this mod was never tested with still starts instead of failing with "Content Configuration Validation Failed".
Each deleted reference is first recorded in cc_pruned_fk (table, column, value), kept for debugging:
  Database.query("gameplay", "SELECT * FROM cc_pruned_fk")  (from the debug console).
In a clean setup the file deletes nothing (vanilla passes validation; the mod's own fixes run before it).
It only covers rows that exist when it runs (end of the mod's cc-merge group, LoadOrder 1000); mods that load
after that are not covered.

Usage: python tools/gen_prune_fk.py [path to Civilization VII]
"""
import os, re, sys

GAME = sys.argv[1] if len(sys.argv) > 1 else r"G:/SteamLibrary/steamapps/common/Sid Meier's Civilization VII"
SCHEMA = os.path.join(GAME, "Base/Assets/schema/gameplay/01_GameplaySchema.sql")
OUT = os.path.join(os.path.dirname(__file__), "..", "mod", "continuous-civ", "data", "3-merge", "95-prune-dangling-fk.sql")
PASSES = 2  # deleting a row can leave rows that pointed at it dangling; a second pass catches those

sql = open(SCHEMA, encoding="utf8").read()
fks = []
for t in re.finditer(r"CREATE TABLE ['\"](\w+)['\"]\s*\((.*?)\n\);", sql, re.S):
    table, body = t.group(1), t.group(2)
    for col, parent, pcol in re.findall(r'FOREIGN KEY \("(\w+)"\) REFERENCES "(\w+)"\("(\w+)"\)', body):
        fks.append((table, col, parent, pcol))
if len(fks) < 500:
    sys.exit(f"only {len(fks)} foreign keys parsed from {SCHEMA}; schema format changed?")

lines = [
    "-- GENERATED by tools/gen_prune_fk.py from the installed game's gameplay schema - do not edit by hand.",
    "-- Safety net for foreign-key validation with untested DLC or mod combinations: rows whose foreign key names",
    "-- something missing are recorded in cc_pruned_fk, then deleted. Deletes nothing in a clean setup.",
    f"-- {len(fks)} foreign keys, {PASSES} passes.",
    "CREATE TABLE IF NOT EXISTS cc_pruned_fk (Pass INTEGER, TableName TEXT, ColumnName TEXT, Value TEXT);",
]
for p in range(1, PASSES + 1):
    lines.append(f"-- pass {p}")
    for table, col, parent, pcol in fks:
        cond = f'"{col}" IS NOT NULL AND "{col}" NOT IN (SELECT "{pcol}" FROM "{parent}" WHERE "{pcol}" IS NOT NULL)'
        lines.append(f"INSERT INTO cc_pruned_fk SELECT {p}, '{table}', '{col}', \"{col}\" FROM \"{table}\" WHERE {cond};")
        lines.append(f'DELETE FROM "{table}" WHERE {cond};')
open(OUT, "w", encoding="utf8", newline="\n").write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(OUT)}: {len(fks)} foreign keys x {PASSES} passes")
